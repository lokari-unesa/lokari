package config

import (
	"log"
	"os"

	"github.com/joho/godotenv"
)

type Config struct {
	Port        string
	DatabaseURL string
}

func LoadConfig() *Config {
	err := godotenv.Load()
	if err != nil {
		log.Println("No .env file found, relying on environment variables")
	}

	port := os.Getenv("PORT")
	if port == "" {
		port = "5181" // Default port
	}

	dbURL := os.Getenv("DATABASE_URL")

	return &Config{
		Port:        port,
		DatabaseURL: dbURL,
	}
}
